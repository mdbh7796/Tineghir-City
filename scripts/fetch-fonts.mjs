#!/usr/bin/env node
// Fetches the exact woff2 files Google Fonts would serve so the site can
// self-host them: no third-party render-blocking CSS, stable preloadable URLs,
// and working typography in the offline Capacitor build.
//
// Run: node scripts/fetch-fonts.mjs
// Writes: public/fonts/*.woff2 + src/fonts.css (@font-face, font-display: swap)
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36';
const FAMILIES = [
  { name: 'Playfair Display', weights: [400, 600, 700] },
  { name: 'Outfit', weights: [300, 400, 500, 600] },
];
const SUBSETS = ['latin', 'latin-ext'];

const api =
  'https://fonts.googleapis.com/css2?' +
  FAMILIES.map((f) => `family=${encodeURIComponent(f.name)}:wght@${f.weights.join(';')}`).join('&') +
  '&display=swap';

const res = await fetch(api, { headers: { 'User-Agent': UA } });
const css = await res.text();
if (!/@font-face/.test(css)) {
  console.error(`unexpected Google Fonts response (${res.status}):\n${css.slice(0, 400)}`);
  process.exit(1);
}

mkdirSync('public/fonts', { recursive: true });
const faces = [];
for (const m of css.matchAll(/\/\*\s*([a-z0-9-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g)) {
  const subset = m[1];
  if (!SUBSETS.includes(subset)) continue;
  const body = m[2];
  const family = /font-family:\s*'?([^';]+)'?;/.exec(body)?.[1]?.trim();
  const weight = /font-weight:\s*(\d+)/.exec(body)?.[1];
  const url = /url\((https:[^)]+\.woff2)\)/.exec(body)?.[1];
  const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1]?.trim();
  if (!family || !weight || !url) continue;
  const slug = family.toLowerCase().replace(/\s+/g, '-');
  const file = `${slug}-${weight}-${subset}.woff2`;
  const buf = Buffer.from(await (await fetch(url, { headers: { 'User-Agent': UA } })).arrayBuffer());
  if (buf.subarray(0, 4).toString('latin1') !== 'wOF2') {
    console.error(`not a woff2 payload: ${url}`);
    process.exit(1);
  }
  writeFileSync(join('public/fonts', file), buf);
  faces.push({ family, weight: Number(weight), file, range, bytes: buf.length });
}

faces.sort((a, b) => a.family.localeCompare(b.family) || a.weight - b.weight || a.file.localeCompare(b.file));
const cssOut =
  [
    '/* Self-hosted webfonts (SIL Open Font License).',
    '   Generated by scripts/fetch-fonts.mjs — edit that script, not this file.',
    "   Paths resolve from public/style.css: public/fonts/<file>.woff2 */",
    ...faces.map(
      (f) =>
        `@font-face {\n  font-family: '${f.family}';\n  font-style: normal;\n  font-weight: ${f.weight};\n  font-display: swap;\n  src: url('./fonts/${f.file}') format('woff2');\n  unicode-range: ${f.range};\n}`
    ),
    '',
  ].join('\n');
writeFileSync('src/fonts.css', cssOut);

writeFileSync(
  'public/fonts/README.md',
  [
    '# Self-hosted webfonts',
    '',
    'Generated by `node scripts/fetch-fonts.mjs` (google/fonts). Do not edit by hand.',
    '',
    '| Family | License |',
    '|---|---|',
    '| Playfair Display | SIL Open Font License 1.1 — https://github.com/clauseggers/Playfair-Display |',
    '| Outfit | SIL Open Font License 1.1 — https://github.com/Outfitio/Outfit-Fonts |',
    '',
    'Both families are distributed under the SIL OFL 1.1, which permits bundling',
    'and self-hosting. Keep this notice with the font files.',
    '',
  ].join('\n')
);

console.log(`fetch-fonts: wrote ${faces.length} face(s) to public/fonts/ and src/fonts.css`);
for (const f of faces) console.log(`  ${f.file}  ${(f.bytes / 1024).toFixed(1)} KB  [${f.family} ${f.weight}]`);
